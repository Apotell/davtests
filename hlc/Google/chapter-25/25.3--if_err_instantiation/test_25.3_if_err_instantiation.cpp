// Expected results follow IEEE 1800-2023 (25.3, 25.3.2, 25.3.3, 23.2.2, 23.3.2, 7.4.2,
// 37); they are not taken from any HLC log. HLC builds the definition model
// (getAllModules(), RefInstance for instances), so the tests navigate module definitions.
//
// What to check: see the CHK/ERR list in the source below.
// Checked:
//   - ERR1 line 40: bus_if u(.*) in m1 where no rst exists -> CompMissingArgument or
//     CompImplicitPortConnectionUndeclared (23.3.2.4: .* needs a matching name for every port)
//   - ERR2 line 46: one_if u(clk, extra) -> CompTooManyPortConnections (more connections than ports)
//   - ERR3 line 52: one_if u(.clock(clk)) -> CompUnknownPort or CompTooManyPortConnections
//   - ERR4 line 59: second instance named u in m4 -> CompDuplicateDeclaration
//   - ERR5 line 64: missing_if u() -> CompUndefinedInterface or UnsupportedTypespec (unknown type)
// Not checked:
//   - The diagnostic codes are HLC's choice; where two codes describe the rule, either is accepted
//
// Source under test (line numbers match the .sv file):
//  17  /*
//  18  :name: if_err_instantiation
//  19  :description: illegal interface instantiations
//  20  :should_fail_because: interface instance connections must match the declared ports and the interface must exist
//  21  :tags: 25.3
//  22  */
//  23
//  24  // Errors in this file:
//  25  //   ERR1: .* used but a port has no matching signal
//  26  //   ERR2: more positional connections than ports
//  27  //   ERR3: named connection to a port that does not exist
