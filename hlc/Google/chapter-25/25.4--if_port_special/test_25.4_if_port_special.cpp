// Tests for tests/Google/chapter-25/25.4--if_port_special.sv
// Expected results follow IEEE 1800-2023 (25.4, 25.6, 25.7, 25.7.2-25.7.4, 23.2.2, 37); they
// are not taken from any HLC log. HLC builds the definition model
// (getAllModules(), RefInstance for instances), so the tests navigate module definitions.
//
// What to check: see the CHK/ERR list in the source below.
// Checked:
//   - CHK1: c1_if(ref int counter) -- direction vpiRef, counter is a variable
//   - CHK2: c2_if(input clk, input en = 1'b1) -- u2 connects only clk; en is left to its default
//   - CHK3: c3_if(clk, a, y) non-ANSI: clk input, a input [7:0], y output; 'logic [7:0] y;' makes y a
//     variable (complete port declaration, 23.2.2.1)
//   - CHK4: c4_if(a, b, y): 'input a, b;' declares a and b on line 52
//   - CHK5: sb_intf1 and sb_intf2 both connect clk to top's clk (one shared net)
//   - No errors: the whole file is legal
// Not checked:
//   - The default value 1'b1 of port en: HLDB has no accessor for a port default (23.2.2.4) -- model gap
//
// Source under test (line numbers match the .sv file):
//  17  /*
//  18  :name: if_port_special
//  19  :description: ref ports, default values, non-ANSI ports and shared port nets
//  20  :tags: 25.4
//  21  */
//  22
//  23  // Checks in this file:
//  24  //   CHK1: ref port on an interface
//  25  //   CHK2: input port with a default value, left unconnected
//  26  //   CHK3: non-ANSI port list with directions in the body
//  27  //   CHK4: non-ANSI directions declared together: input a, b;
//  28  //   CHK5: one clock net shared by two interface instances (LRM simple_bus)
//  29
//  30  // CHK1
//  31  interface c1_if(ref int counter);
//  32    initial counter = 5;
//  33  endinterface
//  34
//  35  // CHK2
//  36  interface c2_if(input logic clk, input logic en = 1'b1);
//  37    logic q;
//  38    always_ff @(posedge clk) if (en) q <= ~q;
//  39  endinterface
//  40
//  41  // CHK3
//  42  interface c3_if(clk, a, y);
//  43    input clk;
//  44    input [7:0] a;
//  45    output [7:0] y;
//  46    logic [7:0] y;
//  47    assign y = a;
//  48  endinterface
//  49
//  50  // CHK4
//  51  interface c4_if(a, b, y);
//  52    input a, b;
//  53    output y;
//  54    assign y = a & b;
//  55  endinterface
//  56
//  57  // CHK5
//  58  interface simple_bus(input logic clk);
//  59    logic req, gnt;
//  60  endinterface
//  61
//  62  module top;
//  63    int counter;
//  64    logic clk = 0;
//  65    logic [7:0] a8, y8;
//  66    logic a, b, y;
//  67    c1_if u1(counter);
//  68    c2_if u2(.clk(clk));
//  69    c3_if u3(clk, a8, y8);
//  70    c4_if u4(a, b, y);
//  71    simple_bus sb_intf1(clk);
//  72    simple_bus sb_intf2(clk);
//  73  endmodule

