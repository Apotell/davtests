// Tests for tests/Google/chapter-25/25.5--mp_err_duplicates.sv
// Expected results follow IEEE 1800-2023 (25.5, 25.5.1-25.5.5, 25.10, 23.3.3, 37); they are
// not taken from any HLC log. HLC builds the definition model
// (getAllModules(), RefInstance for instances), so the tests navigate module definitions.
//
// What to check: see the CHK/ERR list in the source below.
// Checked:
//   - Each duplicate is reported as CompDuplicatePortName or CompDuplicateDeclaration on its line(s):
//   - ERR1 lines 34-35: modport mp declared twice in if_err1
//   - ERR2 line 41: 'input a, a' -- a listed twice (25.5.4: once a port identifier has been defined,
//     there shall not be another port definition with this same name)
//   - ERR3 line 47: a listed as input and as output
//   - ERR4 line 53: .P defined twice
//   - ERR5 line 60: .R(...) reuses the simple port name R
// Not checked:
//   - The diagnostic code is HLC's choice; either duplicate code is accepted
//
// Source under test (line numbers match the .sv file):
//  17  /*
//  18  :name: mp_err_duplicates
//  19  :description: duplicate names inside and between modports
//  20  :should_fail_because: a modport name or modport port identifier shall not be defined twice
//  21  :tags: 25.5
//  22  */
//  23
//  24  // Errors in this file:
//  25  //   ERR1: two modports with the same name in one interface
//  26  //   ERR2: same signal listed twice in one modport
//  27  //   ERR3: same signal listed under two different directions in one modport
//  28  //   ERR4: same port expression name .P defined twice in one modport
//  29  //   ERR5: port expression name equal to a simple port name in the same modport
//  30
//  31  // ERR1
//  32  interface if_err1;
//  33    logic a, b;
//  34    modport mp (input a);
//  35    modport mp (output b);
//  36  endinterface
//  37
//  38  // ERR2
//  39  interface if_err2;
//  40    logic a;
//  41    modport mp (input a, a);
//  42  endinterface
//  43
//  44  // ERR3
//  45  interface if_err3;
//  46    logic a;
//  47    modport mp (input a, output a);
//  48  endinterface
//  49
//  50  // ERR4
//  51  interface if_err4;
//  52    logic [7:0] r;
//  53    modport mp (output .P(r[3:0]), .P(r[7:4]));
//  54  endinterface
//  55
//  56  // ERR5
//  57  interface if_err5;
//  58    logic [7:0] r;
//  59    logic R;
//  60    modport mp (input R, output .R(r[0]));
//  61  endinterface
//  62
//  63  module top;
//  64    if_err1 u1();
//  65    if_err2 u2();
//  66    if_err3 u3();
//  67    if_err4 u4();
//  68    if_err5 u5();
//  69  endmodule

